def log_file_hint(on_date: date | None = None) -> str:
    """Файл журнала за нужный день — тот, куда логи реально пишутся."""
    day = (on_date or date.today()).isoformat()
    try:
        from cvetopt.core.logging_setup import active_log_dir, active_log_suffix

        log_dir = active_log_dir()
        if log_dir is not None:
            return str(log_dir / f"{day}{active_log_suffix()}.log")
    except Exception:
        pass
    return f"data\\logs\\{day}.log"


def _shorten(text: str) -> str:
    if len(text) <= _MAX_UI_LINE_LEN:
        return text
    return text[: _MAX_UI_LINE_LEN - 1].rstrip() + "…"


def humanize_error(raw: str, *, with_hint: bool = True) -> str:
    """Техническое сообщение об ошибке → понятная причина и что делать."""
    text = (raw or "").strip()
    if not text:
        return "Неизвестная ошибка. Подробности в журнале."

    friendly = ""
    for pattern, message in _ERROR_RULES:
        if pattern.search(text):
            friendly = message
            break

    if not friendly:
        friendly = _shorten(text.splitlines()[0].strip())

    if with_hint:
        friendly = f"{friendly} Подробности в журнале: {log_file_hint()}"
    return friendly


def humanize_ui_line(line: str) -> str | None:
    """
    Строка лога → текст для UI, либо None, если показывать её не нужно.
    Полный текст всё равно уходит в файловый журнал.
    """
    text = (line or "").strip()
    if not text:
        return None

    low = text.lower()
    if low.startswith("ошибка"):
        detail = text.split(":", 1)[1].strip() if ":" in text else text
        return f"Ошибка: {humanize_error(detail)}"

    for pattern in _HIDE_PATTERNS:
        if pattern.search(text):
            return None

    for pattern, template in _REWRITE_RULES:
        match = pattern.search(text)
        if match:
            result = template(match) if callable(template) else template.format(*match.groups())
            return _shorten(result)

    if any(marker in low for marker in _KEEP_MARKERS):
        return _shorten(text)

    if low.startswith("страница ") and "заказов в диапазоне" in low:
        return _shorten(text)

    return None
